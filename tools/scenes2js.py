"""Packs the story scene backgrounds (art-gen/scenes/*.png, made with ChatGPT / Gemini) and the AI sticker cut-outs
(art-gen/<album>/slices/*.png, cut by tools/slice_sheet.py) into js/scene-images.js as webp data URIs, so the
one-file build keeps working offline. Run: python tools/scenes2js.py"""
import base64
import glob
import io
import json
import os

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WIDTH = 1024  # the book is at most 440 px wide; 1024 keeps it sharp at 2x
STICKER = 256  # sprites are drawn in a 208 px box


def uri(im, quality):
    buf = io.BytesIO()
    im.save(buf, 'WEBP', quality=quality, method=6)
    return 'data:image/webp;base64,' + base64.b64encode(buf.getvalue()).decode('ascii'), len(buf.getvalue())


out = {}
for path in sorted(glob.glob(os.path.join(ROOT, 'art-gen', 'scenes', '*.png'))):
    im = Image.open(path).convert('RGB')
    im = im.resize((WIDTH, round(im.height * WIDTH / im.width)), Image.LANCZOS)
    name = os.path.splitext(os.path.basename(path))[0]
    out[name], size = uri(im, 78)
    print('%-10s %dx%d  %d KB' % (name, im.width, im.height, size // 1024))

stickers = {}
for folder in sorted(glob.glob(os.path.join(ROOT, 'art-gen', '*', 'slices'))):
    album = os.path.basename(os.path.dirname(folder))
    stickers[album] = []
    for path in sorted(glob.glob(os.path.join(folder, '*.png'))):
        im = Image.open(path).convert('RGBA')
        im.thumbnail((STICKER, STICKER), Image.LANCZOS)
        stickers[album].append(uri(im, 82)[0])
    print('%-10s %d stickers' % (album, len(stickers[album])))

body = ',\n'.join('    %r: %r' % (k, v) for k, v in out.items()).replace("'", '"')
js = ('/* Generated by tools/scenes2js.py from art-gen/scenes/ and art-gen/<album>/slices/. Do not edit by hand. */\n'
      '(function (root) {\n  var PO = root.PO = root.PO || {};\n  PO.SceneImages = {\n' + body + '\n  };\n'
      '  PO.StickerImages = ' + json.dumps(stickers) + ';\n'
      "})(typeof window !== 'undefined' ? window : globalThis);\n")
io.open(os.path.join(ROOT, 'js', 'scene-images.js'), 'w', encoding='utf-8', newline='\n').write(js)
print('wrote js/scene-images.js')
