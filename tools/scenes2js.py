"""Packs the story scene backgrounds (art-gen/scenes/*.png, made with ChatGPT) into js/scene-images.js as webp
data URIs, so the one-file build keeps working offline. Run: python tools/scenes2js.py"""
import base64
import glob
import io
import os

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WIDTH = 1024  # the book is at most 440 px wide; 1024 keeps it sharp at 2x

out = {}
for path in sorted(glob.glob(os.path.join(ROOT, 'art-gen', 'scenes', '*.png'))):
    im = Image.open(path).convert('RGB')
    im = im.resize((WIDTH, round(im.height * WIDTH / im.width)), Image.LANCZOS)
    buf = io.BytesIO()
    im.save(buf, 'WEBP', quality=78, method=6)
    name = os.path.splitext(os.path.basename(path))[0]
    out[name] = 'data:image/webp;base64,' + base64.b64encode(buf.getvalue()).decode('ascii')
    print('%-10s %dx%d  %d KB' % (name, im.width, im.height, len(buf.getvalue()) // 1024))

body = ',\n'.join('    %r: %r' % (k, v) for k, v in out.items()).replace("'", '"')
js = ('/* Generated by tools/scenes2js.py from art-gen/scenes/. Do not edit by hand. */\n'
      '(function (root) {\n  var PO = root.PO = root.PO || {};\n  PO.SceneImages = {\n' + body + '\n  };\n'
      "})(typeof window !== 'undefined' ? window : globalThis);\n")
io.open(os.path.join(ROOT, 'js', 'scene-images.js'), 'w', encoding='utf-8', newline='\n').write(js)
print('wrote js/scene-images.js')
