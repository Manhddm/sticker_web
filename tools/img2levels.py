"""Turns the pixel-art PNGs listed in levels-src/levels.json into Peel Pixel levels (js/image-levels.js).

Each opaque colour in an image becomes one paint colour; fully transparent pixels stay empty. Every colour is
matched to the sticker whose colour is closest, from any album, so the sticker you peel looks like the paint
it brings.

Run: python tools/img2levels.py
Manifest entries: file (required), vi / en (names), and optional triples, wait (waiting-row slots), hard (a Hard level).
"""
import io
import json
import os
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'levels-src')
OUT = os.path.join(ROOT, 'js', 'image-levels.js')

# The main colour of every sticker design, album by album (measured from the drawn sprites in js/art.js;
# the white animals are set by hand because their fur is white). A sticker's id is album * 10 + design.
ALBUM_COLOURS = [
    ['#F85868', '#F8D838', '#A8D858', '#8868E8', '#F89838', '#E83858', '#F85868', '#F8A8A8', '#F8C838', '#F8D848'],
    ['#F888B8', '#F8D8E8', '#C8A8F8', '#F898B8', '#D89858', '#48C8C8', '#E8A858', '#F8E8C8', '#F86848', '#F8D878'],
    ['#F8B848', '#F8D8A8', '#F4F2F4', '#E8C888', '#F88838', '#E6E6EC', '#78D868', '#F8D858', '#B87848', '#F8B8C8'],
    ['#F88848', '#5888E8', '#F868A8', '#F85848', '#F8A858', '#F8C8B8', '#D8A8F8', '#489868', '#F8D858', '#587898'],
    ['#F8B858', '#F86858', '#F8D838', '#F8E888', '#A8B8D8', '#F8D868', '#283868', '#88E888', '#D8E8F8', '#F8D838'],
    ['#F88848', '#F86838', '#E84848', '#F86838', '#48A868', '#F898C8', '#48B8B8', '#D89858', '#F8B838', '#E8F8F8'],
]
MAX_COLOURS = 10


def rgb(h):
    return tuple(int(h[i:i + 2], 16) for i in (1, 3, 5))


def dist(a, b):
    # Weighted RGB distance, close enough to perceived difference for picking a sticker.
    (r1, g1, b1), (r2, g2, b2) = a, b
    rm = (r1 + r2) / 2
    return ((2 + rm / 256) * (r1 - r2) ** 2 + 4 * (g1 - g2) ** 2 + (2 + (255 - rm) / 256) * (b1 - b2) ** 2) ** 0.5


def assign(colours):
    """Greedy one-to-one match of image colours to stickers from any album, closest pairs first.
    Returns {hex: sticker id}."""
    refs = [(a * 10 + d, rgb(h)) for a, row in enumerate(ALBUM_COLOURS) for d, h in enumerate(row)]
    pairs = sorted((dist(rgb(c), r), c, sid) for c in colours for sid, r in refs)
    used_c, used_s, out = set(), set(), {}
    for _, c, sid in pairs:
        if c in used_c or sid in used_s:
            continue
        used_c.add(c); used_s.add(sid); out[c] = sid
    return out


def read(path):
    im = Image.open(path).convert('RGBA')
    w, h = im.size
    px = im.load()
    colours, rows = {}, []
    for y in range(h):
        row = ''
        for x in range(w):
            r, g, b, a = px[x, y]
            if a < 128:
                row += '.'
                continue
            key = '#%02X%02X%02X' % (r, g, b)
            if key not in colours:
                if len(colours) >= MAX_COLOURS:
                    sys.exit('%s has more than %d colours' % (path, MAX_COLOURS))
                colours[key] = 'abcdefghij'[len(colours)]  # never 'k', which means ink
            row += colours[key]
        rows.append(row)
    return w, h, rows, colours


def main():
    manifest = json.load(io.open(os.path.join(SRC, 'levels.json'), encoding='utf-8'))
    levels = []
    for entry in manifest:
        w, h, rows, colours = read(os.path.join(SRC, entry['file']))
        match = assign(list(colours))
        albums = [sid // 10 for sid in match.values()]
        album = max(set(albums), key=albums.count)
        pixels = sum(1 for r in rows for ch in r if ch != '.')
        triples = entry.get('triples') or max(len(colours) * 2, min(12, round(pixels / 10)))
        levels.append({
            'vi': entry.get('vi', entry['file']), 'en': entry.get('en', entry['file']),
            'album': album, 'mixed': True, 'hard': bool(entry.get('hard')), 'triples': triples, 'wait': entry.get('wait', 5),
            'w': w, 'h': h, 'rows': rows,
            'paint': {letter: {'design': match[hexc], 'hex': hexc} for hexc, letter in colours.items()},
        })
        print('%-22s %dx%d  %3d px  %d colours  %d triples  stickers %s' % (entry['file'], w, h, pixels, len(colours), triples, sorted(match.values())))
    body = json.dumps(levels, ensure_ascii=False, indent=2)
    js = ('/* Generated by tools/img2levels.py from levels-src/. Do not edit by hand: change the PNGs or\n'
          '   levels-src/levels.json and run the tool again. */\n'
          '(function (root) {\n  var PO = root.PO = root.PO || {};\n  PO.ImageLevels = ' + body.replace('\n', '\n  ') + ';\n'
          "})(typeof window !== 'undefined' ? window : globalThis);\n")
    io.open(OUT, 'w', encoding='utf-8', newline='\n').write(js)
    print('wrote', os.path.relpath(OUT, ROOT))


if __name__ == '__main__':
    main()
